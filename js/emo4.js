/* v60：捨不得、委屈、嫉妒、擔心四隻怪獸的「特有」做法
   來源：Notion〈捨不得、委屈、嫉妒、擔心的特有應對（Perplexity＋Gemini＋Claude｜2026-11-23）〉
   - 捨不得：在意的是「那一個」人或東西（Hood & Bloom 2008，初步）；固定再見儀式、孩子懂的時間、不偷溜（AAP，專家意見）；
     收玩具單靠預告不一定有用，要陪著收完（Cote 2005、Wilder 2010，小樣本）
   - 委屈：不公平＋被誤會＋沒有力量（馬雨田等 2025，成人）；淡化感受不好（Eisenberg 1996）；道歉之外要補救（Drell & Jaswal 2016）
   - 嫉妒：怕愛被分走的三角關係（Miller 等 2000）；不比較、制止動手同時安撫、每天一對一（AAP、Kennedy & Kramer 2008）
   - 擔心：接納感受＋相信孩子做得到、減少遷就（SPACE，Lebowitz 2020，7–14 歲；遷就統合分析 2021）；勇敢階梯（Rapee 2005，3–5 歲）
   給大人看的文字不寫研究名稱；新增 PARENT[k].tell（容易搞混）、PARENT[k].pro（什麼時候找專業），adult2.js 的 renderParent 會顯示
   載入在 adult2.js 後面 */

